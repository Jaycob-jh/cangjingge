import assert from 'node:assert/strict';
import {createDraftStore,draftStorageKey} from '../../assets/reading-draft-store.mjs';
import {createDraft,importDraft} from '../../assets/reading-intake.mjs';
let raw=null,fail=false;
const storage={getItem:()=>raw,setItem:(k,v)=>{assert.equal(k,draftStorageKey);if(fail)throw Error('QuotaExceededError');raw=v;},removeItem:()=>{raw=null;}};
const store=createDraftStore(storage,importDraft);
const draft=createDraft({title:'测试论文',domain:'tpbm'},{records:[]});
draft.notes='人工备注';draft.original_topics=['sleep'];draft.topics=['sleep','thermal'];
draft.evidence.push({group:'active',field:'波长',value:'810',unit:'nm',locator:'Fig. 2 / PDF 4',pending:true});
draft.reading_scope.pdf_text_extracted_pages=[4];draft.extra_manual={keep:true};
